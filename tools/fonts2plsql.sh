#!/bin/sh
#
# tools/fonts2plsql.sh -- regenerate sql/lib/css_fonts.plsql, the
# @font-face rules of the quiet / dashboard report designs, from the
# vendored font files:
#
#   vendor/fonts/geist-latin-wght-normal.woff2       -> "Geist"
#   vendor/fonts/geist-mono-latin-wght-normal.woff2  -> "Geist Mono"
#
# Each font is a base64 data: URL inside a quoted CSS string, cut into
# 2000-character lines that end in a backslash: in a CSS string a
# backslash followed by a newline is dropped, so the browser reads one
# unbroken URL while every PUT_LINE stays far below SQL*Plus' 2499
# character input line (and PUT_LINE's 32767 byte) limits.  One PL/SQL
# block per font keeps each block small.
#
# Usage:
#   tools/fonts2plsql.sh          rewrite sql/lib/css_fonts.plsql
#   tools/fonts2plsql.sh --check  exit 1 if the committed file is stale
#                                 (lint.sh runs this; nothing is written)
#
# Dev-time only, like tools/js2plsql.sh: the generated file is committed and
# a report run needs nothing but SQL*Plus.  POSIX sh + base64 + tr + fold
# (base64 without flags reads stdin and encodes on GNU, BSD and macOS).
#
set -u
cd "$(dirname "$0")/.." || exit 2

out=sql/lib/css_fonts.plsql
check=0
[ "${1:-}" = "--check" ] && check=1

RANGE='U+0000-00FF,U+0131,U+0152-0153,U+02BB-02BC,U+02C6,U+02DA,U+02DC,U+0304,U+0308,U+0329,U+2000-206F,U+20AC,U+2122,U+2191,U+2193,U+2212,U+2215,U+FEFF,U+FFFD'

face() {  # $1 = family, $2 = woff2 path
    if [ ! -f "$2" ]; then
        echo "fonts2plsql: missing $2" >&2
        return 2
    fi
    printf '%s\n' 'BEGIN'
    printf '    DBMS_OUTPUT.PUT_LINE(%s);\n' \
        "'@font-face{font-family:\"$1\";font-style:normal;font-weight:100 900;font-display:swap;unicode-range:$RANGE;src:url(\"data:font/woff2;base64,\\'"
    base64 < "$2" | tr -d '\n\r' | fold -w 2000 | awk '{ printf "    DBMS_OUTPUT.PUT_LINE(\047%s\\\047);\n", $0 }'
    printf '    DBMS_OUTPUT.PUT_LINE(%s);\n' "'\") format(\"woff2\")}'"
    printf '%s\n' 'END;' '/'
}

gen() {
    cat <<'HDR'
--
-- sql/lib/css_fonts.plsql
--
-- GENERATED by tools/fonts2plsql.sh from vendor/fonts/*.woff2 -- do not
-- edit; run the tool after replacing a font file (lint check 33 fails on
-- a stale copy).  The @font-face rules of the quiet / dashboard designs:
-- Geist and Geist Mono (SIL Open Font License 1.1, vendor/fonts/), Latin
-- subset, variable weight, embedded as base64 so the report stays one
-- offline file.  Each base64 line ends in a backslash: inside a CSS
-- string a backslash + newline is dropped, so the browser reads one URL.
-- Emitted by sql/lib/design_head.sql only; the classic design never
-- includes it.  No tilde below (SET DEFINE tilde).
--
HDR
    printf '%s\n' 'BEGIN' "    DBMS_OUTPUT.PUT_LINE('<style>');" 'END;' '/'
    face "Geist" vendor/fonts/geist-latin-wght-normal.woff2 || return 2
    face "Geist Mono" vendor/fonts/geist-mono-latin-wght-normal.woff2 || return 2
    printf '%s\n' 'BEGIN' "    DBMS_OUTPUT.PUT_LINE('</style>');" 'END;' '/'
}

tmp="${TMPDIR:-/tmp}/fonts2plsql.$$"
trap 'rm -f "$tmp"' EXIT
gen > "$tmp" || exit 2
if [ "$check" -eq 1 ]; then
    if ! cmp -s "$tmp" "$out"; then
        echo "fonts2plsql: $out is stale; run tools/fonts2plsql.sh" >&2
        exit 1
    fi
    exit 0
fi
if cmp -s "$tmp" "$out" 2>/dev/null; then
    echo "$out unchanged"
else
    cp "$tmp" "$out"
    echo "wrote $out"
fi
